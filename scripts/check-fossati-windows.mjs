import assert from 'node:assert/strict';
import fs from 'node:fs';
import { parse } from 'csv-parse/sync';
import { replaceWindowProducts } from '../src/lib/replaceWindowProducts.ts';
import { getWindowCollection, getWindowFamily } from '../src/lib/windowCollections.ts';
import { getCatalogSection, getProductSection } from '../src/lib/catalogSections.ts';
const read = p => JSON.parse(fs.readFileSync(new URL(p, import.meta.url), 'utf8'));
const products = read('../src/data/fossatiProducts.json');
const retired = read('../src/data/retiredWindowNames.json');
const audit = read('../docs/fossati-import-inventory.json');
const catalogues = read('../docs/fossati-catalogue-review.json');
const rows = parse(fs.readFileSync(new URL('../data/catalogo.csv', import.meta.url), 'utf8'), { columns:true });
assert.equal(products.length, 42);
assert.equal(audit.length, 42);
assert.equal(new Set(products.map(p => p.id)).size, 42);
assert.equal(new Set(products.map(p => p.name)).size, 42);
assert.equal(retired.length, 19);
assert.deepEqual(new Set(retired), new Set(rows.filter(r => r.department === 'Infissi' && r.name.startsWith('Infisso ')).map(r => r.name)));
const expectedKeys = ['icon','icon-alu','linea76','linea76-plus','linea76-alu','linea76-alu-plus','vision76','vision76-plus','solaris','solaris-plus','metropolis-battente','metropolis-plus-battente','forma','ishape','iline','iframe','nova-battente','nova-plus-battente','thermicx-battente','thermicx-plus-battente','meridiana82','meridiana82-plus','meridiana-zero','meridiana-zero-plus','meridiana82-alu','meridiana82-alu-plus','metropolis-alzante','metropolis-alzante-plus','metropolis-alzante-slim','metropolis-alzante-slim-plus','inluce','velis','thermicx-alzante','thermicx-alzante-plus','thermicx-alzante-zero','thermicx-alzante-zero-plus','nova-alzante','complanare-pvc','ecoslide','metropolis-complanare','metropolis-complanare-plus','mediterraneo'];
assert.deepEqual(new Set(products.map(p => p.id)), new Set(expectedKeys.map(k => 'fossati-'+k)));
assert.equal(catalogues.catalogues.length, 12);
assert.equal(catalogues.resolved_links.length, 1);
for (const p of products) {
  const fact = audit.find(r => p.id === 'fossati-'+r.key);
  assert(fact, p.name);
  assert.equal(p.department_id, 'infissi');
  assert.deepEqual(p.partner_ids, ['fossati']);
  assert.equal(getProductSection(p), 'serramenti');
  assert.equal(getWindowCollection(p)?.family, 'finestre');
  assert.equal(getWindowCollection(p)?.id, fact.collection);
  assert.equal(p.price, null);
  assert.equal(p.sku, '');
  assert(p.description.length > 100);
  assert.equal(new URL(fact.source_url).hostname, 'www.fossatiserramenti.it');
  assert(catalogues.catalogues.some(c => c.key === fact.catalog_key && c.url === fact.catalog_url));
  const source = catalogues.catalogues.find(c => c.key === fact.catalog_key);
  assert(fact.catalog_pages.length && fact.catalog_pages.every(page => page > 0 && page <= source.pages));
  assert.equal(p.images[0], fact.image.full);
  assert.equal(p.thumbnail, fact.image.thumbnail);
  assert.match(fact.image.sha256, /^[a-f0-9]{64}$/);
  for (const file of [...p.images,p.thumbnail]) {
    const bytes = fs.readFileSync(new URL('../data/immagini/'+file, import.meta.url));
    assert.equal(bytes.subarray(8,12).toString(), 'WEBP');
    assert(bytes.length < 800_000, p.name+': asset weight');
  }
  if (fact.image_scope !== 'model') assert(p.image_note, p.name+': shared/technical image explanation');
}
assert.equal(getCatalogSection('', 'fossati', ''), 'serramenti');
assert.equal(getWindowFamily(new URLSearchParams('partner=fossati')), 'finestre');
assert.equal(getWindowFamily(new URLSearchParams('partner=sallustio')), '');
assert.equal(getWindowFamily(new URLSearchParams('partner=fossati&famiglia=persiane')), 'persiane');
const legacy = rows.map((r,i) => ({...r,id:String(i),department_id:r.department === 'Infissi'?'infissi':'other'}));
const result = replaceWindowProducts(legacy, products);
assert.equal(result.length, legacy.length-19+42);
assert(!result.some(p => p.department_id === 'infissi' && retired.includes(p.name)));
assert(result.filter(p => getWindowCollection(p)?.family === 'finestre').every(p => p.partner_ids?.includes('fossati')));
for (const original of legacy.filter(r => !retired.includes(r.name))) assert(result.includes(original), original.name+': unrequested change');
assert.deepEqual(replaceWindowProducts(result, products), result, 'Repeat import must not duplicate models');
assert(products.find(p => p.name === 'Ecoslide').image_note.includes('Disegno'));
console.log('Fossati: 42/42 sistemi da sito e cataloghi, 19 vecchie finestre rimosse, 8 categorie; immagini locali e altri prodotti preservati.');
